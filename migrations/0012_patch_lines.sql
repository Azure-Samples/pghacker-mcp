-- Patches' lines for search_patches and grep over patches: each distinct
-- line once, by kind ('+' added, '-' removed, ' ' context, 'h' any other
-- line: headers, hunk ranges, text around the diff), without its diff
-- prefix. A patch's lines in order are its text_ids, so a search finds a
-- line in every patch version that has it, and where.

CREATE TABLE patch_texts (
    id    int4 GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    kind  text NOT NULL CHECK (kind IN ('+', '-', ' ', 'h')),
    line  text NOT NULL
);
-- Distinct by content, hashed: some lines are too long for a btree key.
CREATE UNIQUE INDEX patch_texts_kind_line ON patch_texts (kind, md5(line));
CREATE INDEX patch_texts_trgm ON patch_texts USING gin (line gin_trgm_ops);

-- The patch's lines as patch_texts ids, in order; NULL until the
-- patch_lines job indexes it.
ALTER TABLE patches ADD COLUMN text_ids int4[];
CREATE INDEX patches_text_ids ON patches USING gin (text_ids);
CREATE INDEX patches_unindexed ON patches (id) WHERE text_ids IS NULL;
